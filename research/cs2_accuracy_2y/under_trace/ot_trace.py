"""UT-1 addendum (coordinator 2026-10-23, after Codex's f663af8917 OT finding): overtime across ALL P1 lines and tags.

(a) realised rounds / OT per settled line from HLTV map scores (a map is OT when its final score sums to more than 24 rounds, MR12);
    Under hit rate and actual - projection by OT vs non-OT series, by stat / scope / version;
(b) is the PRE-MATCH distribution right about OT-length totals: the model's own distribution (kills: perf.kills_pmf with the
    forecast's lambda and kills spread; HS: perf.hs_pmf with its lambda_kills / HS-per-kill / kills spread) -> PIT and P(Over)
    calibration, overall and by pre-match OT-proneness proxies: both teams' prior OT frequency (HLTV maps in the 365 days before
    the match day), Elo gap (cm-2 lines), market closeness |p - 0.5|;
(c) share of graded Under losses explained by OT (proportional counterfactual: actual x regulation rounds / rounds played < line)
    vs by level.
Diagnostic only; match-grouped bootstrap 95% intervals. usage: python ot_trace.py <scratch dir> > ot_trace.md"""
import collections
import json
import pickle
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[2]))
from report import boot, ci, nm, SCOPE_NAME  # noqa: E402
from build_units import SCOPES  # noqa: E402
import perf  # noqa: E402

REG = 24


def table(out, head, rows):
    out.append("| " + " | ".join(head) + " |")
    out.append("|" + "---|" * len(head))
    out.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)


def hit(u):
    return float(u["over"] if u["side"] == "Over" else 1 - u["over"])


def model_pmf(f, prop, scope, lam_pub):
    pf = (f.get("inputs") or {}).get("perf") or {}
    c = perf.kills_c(pf, scope)
    if prop == "hs":
        return perf.hs_pmf(float(pf["lambda_kills"]), scope, float(pf["hs_per_kill"]), c=c)
    return perf.kills_pmf(float(pf.get("lambda_kills") or lam_pub), scope, c=c)


def main(scr):
    scr = Path(scr)
    us = [u for u in json.load(open(scr / "units.json"))["units"] if u["side"] != "none"]
    fc = {r["id"]: r for r in json.load(open(scr / "p1_fc.json"))["rows"]}
    dump = pickle.load(open(sorted(scr.glob("hltv_dump_*.pkl"))[-1], "rb"))
    maps, team_maps = {}, collections.defaultdict(list)
    for r in dump["rows"]:
        if r[9] is None or r[10] is None:
            continue
        k = (r[0], r[3])
        if k not in maps:
            rr = r[9] + r[10]
            maps[k] = (rr, r[5], r[6])
            d = date.fromisoformat(str(r[1])[:10]).toordinal()
            team_maps[r[5]].append((d, rr > REG))
            team_maps[r[6]].append((d, rr > REG))
    # player's team in the match (from the HLTV rows)
    pteam = {}
    for r in dump["rows"]:
        pteam[(r[0], r[4])] = (r[5], r[6])

    def ot_rate(t, day):
        x = [o for d, o in team_maps.get(t, ()) if day - 365 <= d < day]
        return (sum(x) / len(x), len(x)) if x else (None, 0)

    rows = []
    for u in us:
        mid = u["match"]
        if not (isinstance(mid, str) and mid.startswith("hltv:") and mid[5:].isdigit()) or not u.get("hltv_rounds"):
            continue
        m = int(mid[5:])
        per = [maps.get((m, no)) for no in SCOPES[u["scope"]]]
        if any(p is None for p in per):
            continue
        rr = [p[0] for p in per]
        f = fc[u["forecast_id"]]
        pmf = model_pmf(f, u["prop"], u["scope"], u["lam"])
        a = u["actual"]
        pit = sum(v for y, v in pmf.items() if y < a) + 0.5 * pmf.get(int(a), 0.0)
        pids = [int(v) for v in (u.get("hltv_player_ids") or [])]
        tm = next((pteam[(m, p)] for p in pids if (m, p) in pteam), (None, None))
        day = date.fromisoformat(u["start"][:10]).toordinal()
        o1, n1 = ot_rate(tm[0], day)
        o2, n2 = ot_rate(tm[1], day)
        ci_ = u.get("cm2_inputs") or {}
        rows.append(dict(u, rounds_list=rr, ot=any(x > REG for x in rr), n_ot=sum(x > REG for x in rr),
                         reg_rounds=sum(min(x, REG) for x in rr), pit=pit, sd_model=None,
                         pair_ot=(o1 + o2) / 2 if o1 is not None and o2 is not None and min(n1, n2) >= 10 else None,
                         elo_gap=abs(ci_["elo_own"] - ci_["elo_opp"]) if ci_.get("elo_own") is not None else None,
                         closeness=abs(u["p_team_market"] - 0.5) if u.get("p_team_market") is not None else None))
    out = [f"<!-- generated by ot_trace.py; {len(rows)} P1 lines on canonical HLTV matches with every scope map scored -->"]
    out.append("\n## OT-a. Overtime per settled line (all tags, all P1 lines on HLTV-scored matches)\n")
    out.append("OT series = at least one map in the line's scope went past 24 rounds. 'graded' = 55%+.\n")
    rws = []
    for prop in ("kills", "hs"):
        for sc in ("1", "12", "123"):
            g = [u for u in rows if u["prop"] == prop and u["scope"] == sc]
            if not g:
                continue
            ser = {u["match"]: u["ot"] for u in g}
            for name, x in (("non-OT", [u for u in g if not u["ot"]]), ("OT", [u for u in g if u["ot"]])):
                if not x:
                    continue
                gu = [u for u in x if u["side"] == "Under" and u["conf"] >= .55]
                go = [u for u in x if u["side"] == "Over" and u["conf"] >= .55]
                rws.append([f"{prop} {SCOPE_NAME[sc]}", name, f"{100 * sum(ser.values()) / len(ser):.1f}% of {len(ser)} matches" if name == "OT" else "",
                            nm(x), ci(boot(x, lambda u: u["actual"] - u["lam"])), ci(boot(x, lambda u: u["actual"] - u["line"])),
                            ci(boot(x, lambda u: float(u["over"])), pct=True),
                            f"{nm(gu)}: {ci(boot(gu, hit), pct=True)}" if gu else "-", f"{nm(go)}: {ci(boot(go, hit), pct=True)}" if go else "-"])
    table(out, ["group", "series", "OT share", "lines / matches", "actual - proj", "actual - line", "Over rate", "graded Unders: won", "graded Overs: won"], rws)
    out.append("\nBy version tag (Maps 1-2, both stats, graded lines):\n")
    rws = []
    vs = sorted({u["version"] for u in rows}, key=lambda v: min(u["start"] for u in rows if u["version"] == v))
    for v in vs:
        g = [u for u in rows if u["version"] == v and u["scope"] == "12" and u["conf"] >= .55]
        if len(g) < 10:
            continue
        ser = {u["match"]: u["ot"] for u in g}
        cell = []
        for ot in (False, True):
            gu = [u for u in g if u["ot"] == ot and u["side"] == "Under"]
            cell.append(f"{sum(hit(u) for u in gu):.0f}/{len(gu)} = {100 * sum(hit(u) for u in gu) / len(gu):.1f}%" if gu else "-")
        rws.append([v, f"{sum(ser.values())}/{len(ser)}", nm(g), *cell])
    table(out, ["version", "OT series / matches", "graded lines / matches", "Under won, non-OT", "Under won, OT"], rws)

    out.append("\n## OT-b. Does the pre-match distribution price OT-length totals?\n")
    out.append("PIT = model P(total < actual) + half the mass at the actual. Calibrated: mean 0.5, 10% of lines in each decile, "
               "and P(Over) printed = Over rate. Rows split by PRE-MATCH proxies only (never by the realised OT).\n")
    rws = []

    def blk(lab, x):
        if len(x) < 20:
            return
        top = lambda u: float(u["pit"] >= 0.9)
        bot = lambda u: float(u["pit"] < 0.1)
        rws.append([lab, nm(x), f"{100 * sum(u['ot'] for u in x) / len(x):.1f}%", ci(boot(x, lambda u: u["pit"]), d=3),
                    ci(boot(x, top), pct=True), ci(boot(x, bot), pct=True), f"{100 * sum(u['p'] for u in x) / len(x):.1f}%",
                    ci(boot(x, lambda u: float(u["over"])), pct=True)])
    for prop in ("kills", "hs"):
        g = [u for u in rows if u["prop"] == prop and u["scope"] == "12"]
        blk(f"{prop} M1-2 all", g)
        blk(f"{prop} M1-2 realised non-OT (for reference)", [u for u in g if not u["ot"]])
        blk(f"{prop} M1-2 realised OT (for reference)", [u for u in g if u["ot"]])
        po = sorted(u["pair_ot"] for u in g if u["pair_ot"] is not None)
        if po:
            t1, t2 = po[len(po) // 3], po[2 * len(po) // 3]
            for lab, lo, hi in (("low", -1, t1), ("mid", t1, t2), ("high", t2, 2)):
                blk(f"{prop} M1-2 pair prior OT rate {lab} ({lo if lo >= 0 else 0:.3f}-{min(hi, 1):.3f})",
                    [u for u in g if u["pair_ot"] is not None and lo <= u["pair_ot"] < hi])
        for lab, lo, hi in (("|p-0.5| < 0.1 (close)", 0, .1), ("0.1-0.2", .1, .2), ("0.2+ (lopsided)", .2, 1)):
            blk(f"{prop} M1-2 market {lab}", [u for u in g if u["closeness"] is not None and lo <= u["closeness"] < hi])
        for lab, lo, hi in (("Elo gap < 50", 0, 50), ("50-150", 50, 150), ("150+", 150, 1e9)):
            blk(f"{prop} M1-2 cm-2 {lab}", [u for u in g if u["elo_gap"] is not None and lo <= u["elo_gap"] < hi])
    table(out, ["slice", "lines / matches", "realised OT share", "mean PIT", "PIT >= 0.9 (top decile)", "PIT < 0.1", "mean P(Over) printed",
                "Over rate"], rws)
    out.append("\nRealised OT share vs the pre-match proxy, one row per Maps 1-2 match:\n")
    rws = []
    mm = {}
    for u in rows:
        if u["scope"] == "12" and u["pair_ot"] is not None:
            mm.setdefault(u["match"], u)
    ms = list(mm.values())
    if ms:
        po = sorted(u["pair_ot"] for u in ms)
        t1, t2 = po[len(po) // 3], po[2 * len(po) // 3]
        for lab, lo, hi in (("low", -1, t1), ("mid", t1, t2), ("high", t2, 2)):
            x = [u for u in ms if lo <= u["pair_ot"] < hi]
            rws.append([lab, len(x), f"{sum(u['pair_ot'] for u in x) / len(x):.3f}",
                        f"{100 * (1 - (1 - sum(u['pair_ot'] for u in x) / len(x)) ** 2):.1f}%", ci(boot(x, lambda u: float(u["ot"])), pct=True),
                        ci(boot(x, lambda u: sum(u["rounds_list"]) - 2 * perf.PARAMS["base_r"]))])
    table(out, ["pair prior OT tercile", "matches", "mean per-map prior OT rate", "implied P(OT in 2 maps)", "realised OT series [95% CI]",
                "rounds - 43.48"], rws)

    out.append("\n## OT-c. Graded Under losses: OT vs level\n")
    out.append("OT-explained = the loss becomes a win when his total is scaled to regulation rounds (actual x min(rounds,24) summed / rounds "
               "played) - a proportional counterfactual (kills in OT rounds are not stored per player). Mirror rows for Overs.\n")
    rws = []
    for prop in ("kills", "hs"):
        for sc in ("1", "12", "123"):
            for side in ("Under", "Over"):
                g = [u for u in rows if u["prop"] == prop and u["scope"] == sc and u["side"] == side and u["conf"] >= .55]
                if not g:
                    continue
                lost = [u for u in g if hit(u) == 0]
                won = [u for u in g if hit(u) == 1]
                reg = lambda u: u["actual"] * u["reg_rounds"] / sum(u["rounds_list"])
                if side == "Under":
                    expl = [u for u in lost if u["ot"] and reg(u) < u["line"]]
                    flip = [u for u in won if False]
                else:
                    expl = [u for u in lost if False]
                    flip = [u for u in won if u["ot"] and reg(u) < u["line"]]
                rws.append([f"{prop} {SCOPE_NAME[sc]}", side, nm(g), f"{len(won)}-{len(lost)} ({100 * len(won) / len(g):.1f}%)",
                            f"{sum(u['ot'] for u in lost)} ({100 * sum(u['ot'] for u in lost) / max(1, len(lost)):.0f}%)",
                            f"{len(expl)} ({100 * len(expl) / max(1, len(lost)):.0f}%)" if side == "Under" else f"wins needing OT: {len(flip)}",
                            f"{len(lost) - len(expl)}" if side == "Under" else "-",
                            f"{100 * (len(won) + len(expl)) / len(g):.1f}%" if side == "Under" else f"{100 * (len(won) - len(flip)) / len(g):.1f}%"])
    table(out, ["group", "side", "graded lines / matches", "W-L (won)", "losses in OT series", "losses explained by OT", "level losses",
                "won if no OT rounds (counterfactual)"], rws)
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
